import * as esbuild from "esbuild";
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "api");
const outfile = path.join(outDir, "index.js");

await mkdir(outDir, { recursive: true });
await rm(path.join(outDir, "[...path].js"), { force: true });
await rm(path.join(outDir, "[...path].ts"), { force: true });
await rm(path.join(outDir, "_bundle.mjs"), { force: true });

await esbuild.build({
  entryPoints: [path.join(root, "apps/api/src/vercel-fn.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  outfile,
  packages: "bundle",
  logLevel: "info",
  banner: {
    js: "/* generated by scripts/bundle-api.mjs — do not edit */",
  },
});

await writeFile(
  path.join(outDir, ".gitignore"),
  "index.js\n[...path].js\n_bundle.mjs\n",
  "utf8",
);

console.log(`bundled ${outfile}`);
